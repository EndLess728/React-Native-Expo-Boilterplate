import type { ProjectOptions } from '../options.js';
import type { ProjectFiles } from '../utils/files.js';
import { PM } from './packageManager.js';

/** Writes a README describing exactly the stack this project was generated with. */
export async function writeReadme(files: ProjectFiles, options: ProjectOptions): Promise<void> {
  await files.write('README.md', renderReadme(options));
}

export function renderReadme(o: ProjectOptions): string {
  const ts = o.language === 'ts';
  const x = ts ? 'ts' : 'js';
  const xx = ts ? 'tsx' : 'jsx';
  const run = PM[o.packageManager].run;
  const isRouter = o.navigation === 'expo-router';
  const isRedux = o.state === 'redux';
  const saga = isRedux && o.reduxMiddleware === 'saga';

  const stateLabel = isRedux
    ? `[Redux Toolkit](https://redux-toolkit.js.org/) + ${
        saga ? '[Redux-Saga](https://redux-saga.js.org/)' : 'async thunks'
      } + [redux-persist](https://github.com/rt2zz/redux-persist) on MMKV`
    : '[Zustand](https://github.com/pmndrs/zustand) with MMKV persistence';
  const navLabel = isRouter
    ? '[Expo Router](https://docs.expo.dev/router/introduction/) — file-based routing, typed routes'
    : '[React Navigation 7](https://reactnavigation.org/) — native stack + bottom tabs, typed param lists';

  const tooling = [
    o.eslint ? 'ESLint 9 (flat config)' : null,
    'Prettier',
    o.husky ? 'Husky + lint-staged + Commitlint' : null,
  ]
    .filter(Boolean)
    .join(' + ');

  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(
    `# ${o.displayName}`,
    '',
    'Expo app generated with [create-expo-boilerplate](https://github.com/EndLess728/React-Native-Expo-Boilterplate).',
    '',
    '## Stack',
    '',
    '| Category | Choice |',
    '|---|---|',
    `| **Language** | ${ts ? 'TypeScript (strict)' : 'JavaScript'} |`,
    `| **Navigation** | ${navLabel} |`,
    `| **State** | ${stateLabel} |`,
    '| **Data fetching** | TanStack Query v5 + Axios + react-query-kit |',
    '| **Forms** | React Hook Form + Zod |',
    '| **Styling** | Unistyles 3 — light/dark themes |',
    '| **Storage** | MMKV, AES-encrypted, key kept in the iOS Keychain / Android Keystore |',
    '| **i18n** | i18next + react-i18next (en, es, ar with RTL) |',
    '| **Testing** | jest-expo + React Native Testing Library |',
    `| **Tooling** | ${tooling} |`,
    '',
    '## Getting started',
    '',
    '```bash',
    `${PM[o.packageManager].install}                 # also seeds .env.development / .staging / .production`,
    '$EDITOR .env.development       # fill in your API URLs',
    `${run} android:development     # prebuild + run on Android`,
    `${run} ios:development         # prebuild + run on iOS`,
    '```',
    '',
    '`android/` and `ios/` are generated by `expo prebuild` and are not committed.',
    '',
    '## Project structure',
    '',
    '```',
    '├── src/',
  );

  if (isRouter) {
    push(
      `│   ├── app/                  # Expo Router routes — thin re-exports of feature screens`,
      `│   │   ├── _layout.${xx}       #   bootstrap + providers + <Stack.Protected> auth gating`,
      `│   │   ├── (auth)/login.${xx}`,
      `│   │   └── (tabs)/           #   index → Home, profile → Profile`,
    );
  } else {
    push(
      `│   ├── App.${xx}              # bootstrap + providers + <NavigationContainer>`,
      `│   ├── navigation/           # RootNavigator (auth gating), AuthNavigator, MainTabNavigator,`,
      `│   │                         #   linking config${ts ? ', param-list types' : ''}`,
    );
  }

  push(
    '│   ├── features/             # one folder per feature: screens/, store/, api/, hooks',
    `│   │   ├── auth/             #   index.${x} is the public API — import from '@/features/auth'`,
    '│   │   ├── home/',
    '│   │   ├── posts/            #   api/ — react-query-kit hooks',
    '│   │   └── profile/',
    '│   ├── shared/               # components, hooks, constants, utils used across features',
    '│   ├── providers/            # AppProviders + useAppBootstrap()',
    '│   ├── services/             # Axios client (auth header, 401 handling, error toasts), QueryClient',
    isRedux
      ? `│   ├── store/                # configureStore, redux-persist, ${saga ? 'root saga, ' : ''}typed hooks`
      : '│   ├── store/                # createPersistedStore() + rehydrateStores()',
    '│   ├── storage/              # encrypted MMKV + token helpers',
    '│   ├── localization/         # i18n setup + translations',
    '│   ├── styles/ · theme/      # Unistyles themes, fonts, text styles',
    '│   └── assets/',
    `├── app.config.${x}            # dynamic Expo config (per-environment name / bundle id)`,
    `├── env.${x}                    # validated environment variables (import Env from '@env')`,
    '└── .skills/                  # instructions for AI coding assistants',
    '```',
    '',
    '### Feature boundaries',
    '',
    `Other code imports a feature only through its \`index.${x}\` (\`@/features/auth\`), never a file inside it${
      o.eslint ? ' — ESLint enforces this' : ''
    }. Inside a feature, use relative imports. \`src/store/\` is the one exception: it wires feature state into app start-up.`,
    '',
    'Auth state is exposed as hooks — `useIsLoggedIn()`, `useCurrentUser()`, `useLogin()`, `useLogout()` — plus `signOut()` for non-React code. Screens never touch the store directly.',
    '',
    '## Adding a screen',
    '',
    '1. Create it in its feature:',
    '',
    `   \`\`\`${xx}`,
    `   // src/features/settings/screens/SettingsScreen.${xx}`,
    '   export function SettingsScreen() { /* … */ }',
    '',
    `   // src/features/settings/index.${x}`,
    "   export { SettingsScreen } from './screens/SettingsScreen';",
    '   ```',
    '',
  );

  if (isRouter) {
    push(
      '2. Add a route file — the path is the URL:',
      '',
      `   \`\`\`${x}`,
      `   // src/app/settings.${xx} → /settings`,
      "   export { SettingsScreen as default } from '@/features/settings';",
      '   ```',
      '',
      '   Navigate with `<Link href="/settings">` or `router.push(\'/settings\')` from `expo-router`.',
    );
  } else {
    push(
      `2. Add the route name to \`NAVIGATION\` in \`src/shared/constants/navigation.${x}\`${
        ts ? `, its params to \`src/navigation/types.${x}\`,` : ','
      } and register it in a navigator under \`src/navigation/\`.`,
      '3. Optionally map it to a URL in `src/navigation/linking.' + x + '`.',
      '',
      '   Navigate with `useNavigation().navigate(NAVIGATION.settings)` from `@react-navigation/native`.',
    );
  }

  push('', '## State', '');
  if (!isRedux) {
    push(
      'Each feature owns its Zustand stores in `src/features/<feature>/store/`, created with `createPersistedStore()` (MMKV-backed, `skipHydration: true`).',
      `Register persisted stores in \`rehydrateStores()\` (\`src/store/index.${x}\`), which runs after the encrypted storage is ready.`,
      o.eslint
        ? 'Always select atomically — `useFooStore((s) => s.field)`. ESLint rejects selector-less calls.'
        : 'Always select atomically — `useFooStore((s) => s.field)` — so components only re-render for the field they read.',
    );
  } else {
    push(
      'Each feature owns its slice in `src/features/<feature>/store/`. Add the reducer to `combineReducers` in `src/store/store.' +
        x +
        '` — wrap it in `persistReducer` if it should survive restarts.',
      `Use the typed hooks \`useAppSelector\` / \`useAppDispatch\` from \`@/store\`${
        o.eslint ? ' (ESLint rejects the untyped react-redux ones)' : ''
      }.`,
      '',
      saga
        ? 'Side effects live in sagas: dispatch a `…Request` action, handle it in `src/features/<feature>/store/<feature>Saga.' +
            x +
            '`, and fork the saga in `src/store/rootSaga.' +
            x +
            '`. The auth flow (`loginRequest` → `authSaga` → `loginSuccess` / `loginFailure`) is the reference.'
        : 'Async work uses `createAsyncThunk` — see `login` in `src/features/auth/store/authSlice.' +
            x +
            '`, handled with `extraReducers` and awaited with `.unwrap()`.',
    );
  }

  push(
    '',
    '## API calls',
    '',
    `One hook per file in \`src/features/<feature>/api/\`, built with react-query-kit on the shared Axios \`client\` from \`@/services\`. See \`src/features/posts/api/\` and \`.skills/api-hook-creation.md\`.`,
    '',
    '`src/features/auth/api/authenticate.' +
      x +
      '` is a placeholder login — swap its body for your real endpoint.',
    '',
    '## Environments',
    '',
    '`.env.development`, `.env.staging` and `.env.production` are gitignored and seeded from `.env.example` on install (`' +
      run +
      ' env:init` re-runs it without overwriting). Every `start:*`, `android:*`, `ios:*`, `build:*` and `eas:build:*` script exists per environment.',
    '',
    '## Scripts',
    '',
    '| Script | What it does |',
    '|---|---|',
    `| \`${run} start:development\` | Metro for the dev client |`,
    `| \`${run} android:<env>\` / \`${run} ios:<env>\` | Prebuild and run locally |`,
    `| \`${run} eas:build:<platform>:<env>\` | Cloud build on EAS |`,
    `| \`${run} test\` | Jest |`,
  );
  if (ts) push(`| \`${run} type-check\` | \`tsc --noEmit\` |`);
  if (o.eslint) push(`| \`${run} lint\` / \`${run} lint:fix\` | ESLint |`);
  else push(`| \`${run} format\` / \`${run} format:check\` | Prettier |`);

  if (o.husky) {
    push(
      '',
      '## Git hooks',
      '',
      `- **pre-commit** — blocks direct commits to \`main\`/\`master\`${ts ? ', type-checks,' : ','} and runs lint-staged (${
        o.eslint ? '`eslint --fix`' : '`prettier --write`'
      } on staged files).`,
      '- **commit-msg** — [Conventional Commits](https://www.conventionalcommits.org/) via Commitlint (`feat: …`, `fix: …`).',
      `- **post-merge** — reinstalls dependencies when the lockfile changed.`,
    );
  }

  push(
    '',
    '## AI assistant skills',
    '',
    '`.skills/` holds task-specific instructions (API hooks, UI, localization) for Claude, Cursor and friends — reference them in prompts, e.g. `@.skills/api-hook-creation.md`.' +
      (ts ? '' : ' Their code samples are TypeScript; drop the type annotations.'),
    '',
  );

  return `${lines.join('\n')}\n`;
}
